"""Translate ics-openvpn UI resources (values/strings.xml, arrays.xml, plurals.xml) to Indonesian (values-in) with Qwen3-4B
on bamboo's llama serve (127.0.0.1:8080). Run on bamboo:  python3 translate_strings.py <in_dir> <out_dir>
Every translation is validated: printf placeholders, HTML tags, \\n / \\' / \\" escapes and URLs must survive unchanged,
otherwise the English text is kept. Output files contain only translated entries (Android falls back to English for the rest).
Source of truth: C:\\Projects\\AWSOpenVPN\\tools (AWSOpenVPN, Created by MR.TRYCATCH @ CODEMARVEL INDONESIA)."""
import json, os, re, sys, time, urllib.request
from collections import Counter

LLAMA = "http://127.0.0.1:8080/v1/chat/completions"
SYSTEM = ("You translate Android app user-interface strings of an OpenVPN client from English to Indonesian (Bahasa Indonesia). "
          "Use clear, natural, concise UI Indonesian. Keep technical terms in English where Indonesians use them: VPN, OpenVPN, "
          "TLS, SSL, DNS, IP, IPv4, IPv6, MTU, TCP, UDP, proxy, server, client, profile names, certificate formats, file names, LZO, "
          "keystore, PKCS12, Always-on, OpenSSL, mbed TLS, app names. "
          "Copy EXACTLY and keep in place: printf placeholders like %s %d %1$s %2$d %%, escape sequences \\n \\' \\\", HTML tags like <b> </b> <a href=\"...\">, "
          "URLs, and anything inside backticks. Do not add quotes, notes or explanations. Output only the Indonesian translation.")
PLACEHOLDER = re.compile(r"%(?:\d+\$)?[-#+ 0,(]*\d*(?:\.\d+)?[a-zA-Z%]")
TAG = re.compile(r"</?[a-zA-Z][^>]*>")
URL = re.compile(r"https?://[^\s<\"']+")

def ask(text):
    body = {"model": "x", "temperature": 0.1, "max_tokens": 900, "messages": [{"role": "system", "content": SYSTEM}, {"role": "user", "content": text}]}
    req = urllib.request.Request(LLAMA, json.dumps(body).encode(), {"Content-Type": "application/json"})
    out = json.load(urllib.request.urlopen(req, timeout=120))["choices"][0]["message"]["content"]
    return re.sub(r"<think>.*?</think>", "", out, flags=re.S).strip()

def fix_escapes(s):
    """Android string rules: escape bare apostrophes/quotes; keep existing escapes."""
    s = re.sub(r"(?<!\\)'", r"\\'", s)
    s = re.sub(r'(?<!\\)"(?![^<]*>)', r'\\"', s)  # quotes outside tags
    if s[:1] in "@?":
        s = "\\" + s
    return s

def valid(src, dst):
    if not dst or dst == src:
        return False
    for pattern in (PLACEHOLDER, TAG, URL):
        if Counter(pattern.findall(src)) != Counter(pattern.findall(dst)):
            return False
    return src.count("\\n") == dst.count("\\n") and "<![CDATA[" not in dst + src

def translate(raw, stats):
    if not raw.strip() or raw.strip().startswith("@") or not re.search(r"[A-Za-z]{2}", raw):
        return None
    try:
        dst = fix_escapes(ask(raw))
    except Exception:
        stats["error"] += 1
        return None
    if valid(raw, dst):
        stats["ok"] += 1
        return dst
    stats["rejected"] += 1
    return None

def run(in_dir, out_dir):
    os.makedirs(out_dir, exist_ok=True)
    stats = Counter()
    start = time.time()
    # strings.xml
    text = open(os.path.join(in_dir, "strings.xml"), encoding="utf-8").read()
    out = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Generated by tools/translate_strings.py (Qwen3-4B on bamboo), validated; review welcome. -->", "<resources>"]
    for m in re.finditer(r'<string\s+name="([^"]+)"([^>]*)>(.*?)</string>', text, re.S):
        name, attrs, raw = m.group(1), m.group(2), m.group(3)
        if 'translatable="false"' in attrs:
            continue
        dst = translate(raw, stats)
        if dst is not None:
            extra = ' formatted="false"' if 'formatted="false"' in attrs else ""
            out.append(f'    <string name="{name}"{extra}>{dst}</string>')
        print(stats["ok"] + stats["rejected"] + stats["error"], name, "ok" if dst else "keep-en", flush=True)
    out.append("</resources>")
    open(os.path.join(out_dir, "strings.xml"), "w", encoding="utf-8").write("\n".join(out) + "\n")
    # arrays.xml (translatable string-arrays only)
    path = os.path.join(in_dir, "arrays.xml")
    if os.path.exists(path):
        text = open(path, encoding="utf-8").read()
        out = ['<?xml version="1.0" encoding="utf-8"?>', "<resources>"]
        for m in re.finditer(r'<string-array\s+name="([^"]+)"([^>]*)>(.*?)</string-array>', text, re.S):
            if 'translatable="false"' in m.group(2):
                continue
            items = re.findall(r"<item>(.*?)</item>", m.group(3), re.S)
            done = [translate(i, stats) for i in items]
            if items and all(d is not None for d in done):
                out.append(f'    <string-array name="{m.group(1)}">')
                out += [f"        <item>{d}</item>" for d in done]
                out.append("    </string-array>")
        out.append("</resources>")
        open(os.path.join(out_dir, "arrays.xml"), "w", encoding="utf-8").write("\n".join(out) + "\n")
    # plurals.xml
    path = os.path.join(in_dir, "plurals.xml")
    if os.path.exists(path):
        text = open(path, encoding="utf-8").read()
        out = ['<?xml version="1.0" encoding="utf-8"?>', "<resources>"]
        for m in re.finditer(r'<plurals\s+name="([^"]+)"[^>]*>(.*?)</plurals>', text, re.S):
            items = re.findall(r'<item quantity="([^"]+)">(.*?)</item>', m.group(2), re.S)
            other = next((t for q, t in items if q == "other"), items[-1][1] if items else "")
            d = translate(other, stats)
            if d is not None:
                out.append(f'    <plurals name="{m.group(1)}">')
                out.append(f'        <item quantity="other">{d}</item>')  # Indonesian has no plural forms
                out.append("    </plurals>")
        out.append("</resources>")
        open(os.path.join(out_dir, "plurals.xml"), "w", encoding="utf-8").write("\n".join(out) + "\n")
    print("DONE", dict(stats), f"{time.time() - start:.0f}s", flush=True)

if __name__ == "__main__":
    run(sys.argv[1], sys.argv[2])
